"""Paired comparisons between experiments: is model A really better than model B?

Overlapping 95% CIs do not answer this, because both models are scored on the same slides.
Here every bootstrap sample draws one set of patients and scores A and B on it, so the
interval is for the *difference* A − B. A difference whose interval excludes 0 is reported
as significant (p is the two-sided bootstrap p-value, no correction for multiple comparisons).

  uv run python scripts/32_compare.py      → results/tables/comparisons.{csv,md}
"""
import importlib.util
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from lungclam import metrics as M  # noqa: E402
from lungclam import paths  # noqa: E402

_spec = importlib.util.spec_from_file_location("ev", Path(__file__).with_name("30_evaluate.py"))
ev = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(ev)

SPLITS = {"cv": ("val", ["macro_auc", "luad_vs_lusc_auc"]),
          "external": ("external", ["luad_vs_lusc_auc", "tumor_sensitivity"])}


def pairs() -> list[tuple[str, str]]:
    out = []
    for lf in ["_lf10", "_lf25", "_lf50", ""]:
        out += [(f"clam_sb_phikon{lf}", f"meanpool_phikon{lf}"), (f"clam_sb_phikon{lf}", f"abmil_phikon{lf}")]
    out += [("clam_sb_phikon", "clam_mb_phikon"), ("clam_sb_phikon", "maxmil_phikon"),
            ("abmil_phikon", "meanpool_phikon")]
    return out


def paired_bootstrap(a: pd.DataFrame, b: pd.DataFrame, metric, n: int = 1000, seed: int = 0) -> dict:
    a, b = a.sort_values("slide_id").reset_index(drop=True), b.sort_values("slide_id").reset_index(drop=True)
    assert (a.slide_id.values == b.slide_id.values).all()
    rows = list(a.groupby("patient_id").indices.values())
    rng = np.random.default_rng(seed)
    diffs = []
    for _ in range(n):
        idx = np.concatenate([rows[i] for i in rng.integers(0, len(rows), len(rows))])
        try:
            diffs.append(metric(a.iloc[idx]) - metric(b.iloc[idx]))
        except ValueError:
            continue
    d = np.array(diffs, dtype=float)
    d = d[np.isfinite(d)]
    p = min(1.0, 2 * min((d <= 0).mean(), (d >= 0).mean()))
    return {"diff": metric(a) - metric(b), "lo": np.percentile(d, 2.5), "hi": np.percentile(d, 97.5), "p": p}


def main():
    cache, rows = {}, []
    for a, b in pairs():
        for name in (a, b):
            if name not in cache:
                cache[name] = ev.load_preds(name)
        for split, (raw, metrics) in SPLITS.items():
            da, db = (ev.average(cache[n][cache[n].split == raw]) for n in (a, b))
            if da.empty or db.empty:
                continue
            for m in metrics:
                r = paired_bootstrap(da, db, M.METRICS[m])
                rows.append({"a": a, "b": b, "split": split, "metric": m, **r})
                print(f"{split:8s} {m:18s} {a:22s} − {b:22s} {r['diff']:+.3f} ({r['lo']:+.3f} to {r['hi']:+.3f}) p={r['p']:.3f}")
    tab = pd.DataFrame(rows)
    out = paths.RESULTS / "tables"
    tab.to_csv(out / "comparisons.csv", index=False)
    tab["A − B (95% CI)"] = tab.apply(lambda r: f"{r['diff']:+.3f} ({r.lo:+.3f} to {r.hi:+.3f})", axis=1)
    tab["p"] = tab.p.map(lambda p: "<0.001" if p < 0.001 else f"{p:.3f}")
    tab["sig."] = np.where((tab.lo > 0) | (tab.hi < 0), "yes", "")
    md = ["# Paired comparisons", "", "Patient-level paired bootstrap (1000 draws) of the difference A − B, "
          "scored on the same slides. Generated by `scripts/32_compare.py`.", ""]
    for (split, metric), g in tab.groupby(["split", "metric"], sort=False):
        md += [f"### {split}: {metric}", "", g[["a", "b", "A − B (95% CI)", "p", "sig."]].to_markdown(index=False), ""]
    (out / "comparisons.md").write_text("\n".join(md))
    print("saved results/tables/comparisons.{csv,md}")


if __name__ == "__main__":
    main()
